let current = $state<Locale>('zh-CN');
let initialized = false;

function preferredLocale(): Locale {
  if (typeof window === 'undefined') return 'zh-CN';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'zh-CN' || stored === 'en-US') return stored;
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

function applyLocale(locale: Locale, persist: boolean): void {
  current = locale;
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
  if (persist && typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, locale);
}

export const i18n = {
  get locale(): Locale {
    return current;
  },
  init(): void {
    if (initialized) return;
    initialized = true;
    applyLocale(preferredLocale(), false);
  },
  set(locale: Locale): void {
    applyLocale(locale, true);
  },
  toggle(): void {
    applyLocale(current === 'zh-CN' ? 'en-US' : 'zh-CN', true);
  },
};

export function t(source: string, values: Record<string, string | number> = {}): string {
  const template = current === 'en-US' ? english[source] || source : source;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function localeCode(): Locale {
  return current;
}
